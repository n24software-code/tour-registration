const PINNED = 'SA';
const collator = new Intl.Collator('en', { sensitivity: 'base' });

/** A–Z by label, with Saudi first. */
export const NATIONALITIES: Nationality[] = [
  RAW.find((n) => n.code === PINNED)!,
  ...RAW.filter((n) => n.code !== PINNED).sort((a, b) => collator.compare(a.label, b.label)),
];

const BY_CODE = new Map(NATIONALITIES.map((n) => [n.code, n]));

export const isNationalityCode = (code: string) => BY_CODE.has(code);

/** The demonym for a stored code. Unknown or missing codes fall back to an em dash. */
export const nationalityLabel = (code?: string | null) =>
  (code && BY_CODE.get(code)?.label) || (code ? code : '—');

/** "Iraqi, Yemeni, Lebanese or Syrian" — keeps the order the tour stored. */
export function nationalityList(codes: readonly string[]) {
  const labels = codes.map((c) => BY_CODE.get(c)?.label ?? c);
  if (labels.length <= 1) return labels[0] ?? '';
  return `${labels.slice(0, -1).join(', ')} or ${labels[labels.length - 1]}`;
}
